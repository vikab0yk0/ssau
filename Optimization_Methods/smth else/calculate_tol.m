function tol = calculate_tol(f, a, b, eps)
% CALCULATE_TOL Вычисление оптимального параметра tol для методов оптимизации
%
% Разложение в ряд Тейлора вокруг точки x0 (середины [a,b]):
% f(x1) = f(x0-ϵ) = f(x0) - ϵ*f'(x0) + ϵ^2/2 * f''(x0) - ϵ^3/6 * f'''(ξ1)
% f(x2) = f(x0+ϵ) = f(x0) + ϵ*f'(x0) + ϵ^2/2 * f''(x0) + ϵ^3/6 * f'''(ξ2)
% Δf = f(x2)-f(x1) = 2*ϵ*f'(x0) + ϵ^3/6 * [f'''(ξ1)+f'''(ξ2)]
%
% Пусть x* – точка экстремума, f'(x*)=0. Если x0=x*+δ, где δ – малая величина:
% f'(x0) = f''(x*)δ + O(δ^2)
% δ ≈ расстояние от x0 до x* ≈ ϵ  ==>  δ = O(ϵ)
%
% ||==> Δf = 2*ϵ*[f''(x*)*O(ϵ)] + O(ϵ^3) = O(ϵ^2*f''(x*)) + O(ϵ^3)
% Δf ≈ 2*ϵ^2*f''(x*)   <---- все рассуждения чисто ради этой строчки
%
% Входные параметры:
%   f   - функция, для которой вычисляется tol
%   a,b - границы интервала
%   eps - параметр метода (отступ от середины)
%
% Выходные параметры:
%   tol - оптимальное значение параметра остановки

    x0 = (a + b) / 2;
    dx = 1e-6;
   
    % конечно-разностная аппроксимация второй производной
    df = abs((f(x0 + dx) - 2*f(x0) + f(x0 - dx)) / dx^2);
    
    tol = max(1e-12, min(2 * eps.^2 * df, 1e-3));
end